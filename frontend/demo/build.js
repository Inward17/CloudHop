// Builds the GitHub Pages demo: the real dashboard plus demo.js, which answers /api calls
// in the browser. demo.js reuses the backend's own modules, so the demo behaves like the real thing.
// Usage: node backend/scripts/bundle.js && node frontend/demo/build.js <out-dir>
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = process.argv[2] ?? '_site';
const publicDir = new URL('../public/', import.meta.url);
const backendSrc = new URL('../../backend/src/', import.meta.url);
// Dependency order: each module may import only from those before it.
const MODULES = ['templates.gen.js', 'analyze.js', 'store.js', 'portability.js', 'plans.js', 'intent.js', 'generate.js', 'github.js', 'providers.js'];

// A tiny bundler for our own plain ES modules: each file becomes a function returning its exports.
function wrap(name, source) {
  const imports = [...source.matchAll(/^import \{([^}]+)\} from '\.\/([^']+)';$/gm)];
  const names = [];
  const body = source
    .replace(/^import .*$/gm, '')
    .replace(/^export (async function|function|const|let|class) (\w+)/gm, (_, kind, id) => { names.push(id); return `${kind} ${id}`; });
  const header = imports.map(([, list, from]) => `const {${list}} = modules['${from}'];`).join('\n');
  return `modules['${name}'] = (() => {\n${header}\n${body}\nreturn { ${names.join(', ')} };\n})();`;
}

const bundle = [
  '// Generated by frontend/demo/build.js. Demo only: answers /api calls with sample data.',
  '(() => {',
  'const modules = {};',
  // Browsers refuse a custom User-Agent header, so drop it from GitHub calls made by the shared modules.
  'const browserFetch = window.fetch.bind(window);',
  'const fetch = (url, options = {}) => { const headers = { ...(options.headers ?? {}) }; delete headers["User-Agent"]; return browserFetch(url, { ...options, headers }); };',
  ...MODULES.map((name) => wrap(name, readFileSync(new URL(name, backendSrc), 'utf8'))),
  readFileSync(new URL('mock.js', import.meta.url), 'utf8'),
  '})();',
].join('\n');

mkdirSync(out, { recursive: true });
for (const file of readdirSync(publicDir)) {
  if (file === '_headers') continue; // Cloudflare Pages only.
  copyFileSync(new URL(file, publicDir), join(out, file));
}
writeFileSync(join(out, 'demo.js'), bundle);
const index = readFileSync(new URL('index.html', publicDir), 'utf8');
if (!index.includes('<script src="charts.js"></script>')) throw new Error('index.html changed: update the demo script injection');
writeFileSync(join(out, 'index.html'), index
  .replace('<title>Cloudhop</title>', '<title>Cloudhop demo</title>')
  .replace('<script src="charts.js"></script>', '<script src="demo.js"></script>\n<script src="charts.js"></script>'));
writeFileSync(join(out, '.nojekyll'), '');
console.log(`Demo built in ${out}`);
