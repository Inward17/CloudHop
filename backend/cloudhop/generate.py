"""Turns a service map into the files committed to the user's repo, for review in a PR."""
import json
import re

from .templates import TEMPLATES

DEPLOYABLE_STORES = {'postgres', 'redis'}


def deploy_issues(service_map):
    issues = []
    if not service_map['services']:
        issues.append('No runnable service was found.')
    for store in service_map['datastores']:
        if store['kind'] not in DEPLOYABLE_STORES:
            issues.append(f"{store['kind']} cannot be deployed yet. Postgres and Redis work.")
    for service in service_map['services']:
        if service['runtime'] not in ('node', 'python') and not service['hasDockerfile']:
            issues.append(f"{service['path']} needs a Dockerfile, because {service['runtime']} has no built-in build support.")
    return issues


def _slug(text):
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', text.lower()))


def _base36(number):
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    out = ''
    while True:
        number, rest = divmod(number, 36)
        out = digits[rest] + out
        if number == 0:
            return out


def project_slug(repo):
    """Short and unique per repo, so two projects named "app" under different owners never share cloud names."""
    value = 2166136261  # 32-bit FNV-1a, same result as the original JavaScript.
    for char in repo.lower():
        code = ord(char)
        if code > 0xFFFF:
            code = 0xD800 + ((code - 0x10000) >> 10)
        value = ((value ^ code) * 16777619) & 0xFFFFFFFF
    name = re.sub(r'-$', '', _slug(repo.split('/')[-1])[:16])
    return f'{name}-{_base36(value)[:4]}'


def resource_name(repo):
    return f'cloudhop-{project_slug(repo)}'


def _service_port(service):
    if service.get('port'):
        return service['port']
    if service['kind'] == 'static':
        return 80
    return 8000 if service['runtime'] == 'python' else 3000


PYTHON_START = {
    'FastAPI': lambda port: f'["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "{port}"]',
    'Flask': lambda port: f'["flask", "run", "--host", "0.0.0.0", "--port", "{port}"]',
    'Django': lambda port: f'["python", "manage.py", "runserver", "0.0.0.0:{port}"]',
}


def dockerfile_for(service):
    port = _service_port(service)
    review = '# Generated by Cloudhop. Check the start command before merging.\n'
    if service['kind'] == 'static':
        output = 'build' if service.get('framework') == 'Create React App' else 'dist'
        return f'{review}FROM node:22-slim AS build\nWORKDIR /app\nCOPY . .\nRUN npm ci || npm install\nRUN npm run build\n\nFROM nginx:alpine\nCOPY --from=build /app/{output} /usr/share/nginx/html\nEXPOSE 80\n'
    if service['runtime'] == 'python':
        start = PYTHON_START.get(service.get('framework'), PYTHON_START['FastAPI'])(port)
        return f'{review}FROM python:3.12-slim\nWORKDIR /app\nCOPY . .\nRUN if [ -f requirements.txt ]; then pip install -r requirements.txt; else pip install .; fi\nENV PORT={port}\nEXPOSE {port}\nCMD {start}\n'
    return f'{review}FROM node:22-slim\nWORKDIR /app\nCOPY . .\nRUN npm ci || npm install\nRUN npm run build --if-present\nENV PORT={port}\nEXPOSE {port}\nCMD ["npm", "start"]\n'


def app_services(service_map):
    # First web service gets port 80, so a backend beats a static frontend for the main address.
    ordered = sorted(service_map['services'], key=lambda service: 0 if service['kind'] == 'web' else 1)
    return [{
        'name': 'app' if service['path'] == '.' else f"app-{_slug(service['path'])}",
        'path': service['path'],
        'port': _service_port(service),
        'publicPort': 80 if index == 0 else 8080 + index,
    } for index, service in enumerate(ordered)]


def compose_for(service_map):
    kinds = {store['kind'] for store in service_map['datastores']}
    has_postgres, has_redis = 'postgres' in kinds, 'redis' in kinds
    depends_on = (['db'] if has_postgres else []) + (['redis'] if has_redis else [])
    env = (['      DATABASE_URL: postgres://app:${DB_PASSWORD}@db:5432/app'] if has_postgres else []) + (['      REDIS_URL: redis://redis:6379'] if has_redis else [])
    lines = ['# Generated by Cloudhop.', 'services:']
    for service in app_services(service_map):
        lines += [
            f"  {service['name']}:",
            f"    build: ./src{'' if service['path'] == '.' else '/' + service['path']}",
            '    restart: unless-stopped',
            '    env_file: .env',
            f"    ports: [\"{service['publicPort']}:{service['port']}\"]",
        ]
        if env:
            lines += ['    environment:', *env]
        if depends_on:
            lines.append(f"    depends_on: [{', '.join(depends_on)}]")
    if has_postgres:
        lines += [
            '  db:',
            '    image: postgres:16',
            '    restart: unless-stopped',
            '    environment:',
            '      POSTGRES_USER: app',
            '      POSTGRES_DB: app',
            '      POSTGRES_PASSWORD: ${DB_PASSWORD}',
            '    volumes: [db:/var/lib/postgresql/data]',
            '    healthcheck:',
            '      test: [CMD, pg_isready, -U, app]',
            '      interval: 5s',
            '      retries: 20',
        ]
    if has_redis:
        lines += ['  redis:', '    image: redis:7', '    restart: unless-stopped']
    if has_postgres:
        lines += ['volumes:', '  db:']
    return '\n'.join(lines) + '\n'


def cloud_config(cloud, data, repo):
    """Role, pool and service account are named per project, so several projects can share one cloud account."""
    name = project_slug(repo)
    if cloud == 'aws':
        return {
            'region': data.get('region'),
            'accountId': data.get('accountId'),
            'roleArn': f"arn:aws:iam::{data.get('accountId')}:role/cloudhop-{name}-deploy",
            'stateBucket': f"cloudhop-state-{data.get('accountId')}",
        }
    return {
        'region': data.get('region'),
        'projectId': data.get('projectId'),
        'projectNumber': data.get('projectNumber'),
        'workloadIdentityProvider': f"projects/{data.get('projectNumber')}/locations/global/workloadIdentityPools/ch-{name}/providers/ci",
        'serviceAccount': f"ch-{name}@{data.get('projectId')}.iam.gserviceaccount.com",
        'stateBucket': f"{data.get('projectId')}-cloudhop-state",
    }


# Which CI identity the clouds trust. Each CI issues its own OIDC tokens; AWS and GCP accept a
# token only from this repo (and branch or environment where the CI puts that in the token).
SAFE = re.compile(r'^[\w.\-/{}:* ]+$', re.ASCII)


def trust_for(provider, info):
    if provider == 'github':
        subject = f"repo:{info['repo']}:environment:cloudhop"
        trust = {'issuer': 'token.actions.githubusercontent.com', 'gcpIssuer': 'https://token.actions.githubusercontent.com', 'awsAudience': 'sts.amazonaws.com', 'gcpAudience': '', 'subject': subject, 'gcpCondition': f"assertion.sub == '{subject}'"}
    elif provider == 'gitlab':
        subject = f"project_path:{info['repo']}:ref_type:branch:ref:{info['defaultBranch']}"
        trust = {'issuer': 'gitlab.com', 'gcpIssuer': 'https://gitlab.com/', 'awsAudience': 'https://gitlab.com', 'gcpAudience': 'https://gitlab.com', 'subject': subject, 'gcpCondition': f"assertion.sub == '{subject}'"}
    elif provider == 'bitbucket':
        issuer = f"api.bitbucket.org/2.0/workspaces/{info['workspace']}/pipelines-config/identity/oidc"
        audience = f"ari:cloud:bitbucket::workspace/{re.sub(r'[{}]', '', info['workspaceUuid'])}"
        trust = {'issuer': issuer, 'gcpIssuer': f'https://{issuer}', 'awsAudience': audience, 'gcpAudience': audience, 'subject': f"{info['repositoryUuid']}*", 'gcpCondition': f"assertion.sub.startsWith('{info['repositoryUuid']}')"}
    elif provider == 'azure':
        subject = f"sc://{info['organization']}/{info['project']}/cloudhop"
        issuer = f"vstoken.dev.azure.com/{info['organizationId']}"
        trust = {'issuer': issuer, 'gcpIssuer': f'https://{issuer}', 'awsAudience': 'api://AzureADTokenExchange', 'gcpAudience': 'api://AzureADTokenExchange', 'subject': subject, 'gcpCondition': f"assertion.sub == '{subject}'"}
    else:
        raise ValueError(f'Unknown provider {provider}')
    # These values go into a CloudFormation file and a shell script, so refuse anything that could break out.
    for value in (trust['issuer'], trust['awsAudience'], trust['gcpAudience'], trust['subject']):
        if value and not SAFE.fullmatch(value):  # fullmatch: Python's $ would also accept a trailing newline.
            raise ValueError('Repository details contain characters Cloudhop cannot put in a setup file')
    return trust


def _matches(pattern, value):
    return isinstance(value, str) and re.fullmatch(pattern, value, re.ASCII) is not None


def validate_cloud_input(cloud, data):
    """These values end up in generated files and scripts, so only safe characters pass."""
    data = data if isinstance(data, dict) else {}
    region = _matches(r'[a-z]+-[a-z]+\d?(-\d)?', data.get('region'))
    if cloud == 'aws':
        return region and _matches(r'\d{12}', data.get('accountId'))
    if cloud == 'gcp':
        return region and _matches(r'[a-z][a-z0-9-]{4,28}[a-z0-9]', data.get('projectId')) and _matches(r'\d{6,20}', data.get('projectNumber'))
    return False


# What the setup files grant, in plain words. Keep in step with bootstrap-aws.yml and bootstrap-gcp.sh.
CLOUD_GRANTS = {
    'aws': [
        ['EC2, all actions', 'Create, change and delete servers, disks, networks and firewalls anywhere in the account.'],
        ['Systems Manager', 'Run commands on servers and read parameters.'],
        ['S3', 'Only buckets named cloudhop-*.'],
        ['IAM', 'Only roles and instance profiles named cloudhop-*-vm, and checking its own permissions. It cannot change its own role.'],
        ['Billing', 'Read month-to-date cost and credits.'],
    ],
    'gcp': [
        ['Compute Admin', 'Create, change and delete VMs, disks, networks and firewalls anywhere in the project.'],
        ['Storage Admin', 'Every bucket in the project.'],
        ['Service Account Admin and User', 'Create service accounts and run VMs as them.'],
        ['IAP tunnel and OS Admin Login', 'Reach VMs through IAP and sign in to them as admin.'],
    ],
}


def projects_using_cloud(account, projects):
    """Projects whose setup targets this cloud account. `account['data']` and `project['clouds']` are parsed."""
    key = 'accountId' if account['kind'] == 'aws' else 'projectId'
    return [project for project in projects if (project['clouds'].get(account['kind']) or {}).get(key) == account['data'].get(key)]


def cloud_access(account, projects, reports):
    """What the setup file grants, which repos' CI can use the account, and the latest live permission check."""
    using = projects_using_cloud(account, projects)
    repo_of = {project['id']: project['repo'] for project in using}
    checks = [report for report in reports
              if report.get('event') == 'access' and report.get('cloud') == account['kind'] and report.get('projectId') in repo_of and isinstance(report.get('checks'), list)]
    last = max(checks, key=lambda report: report['at'], default=None)
    return {
        'kind': 'cloud',
        'grants': CLOUD_GRANTS[account['kind']],
        'repos': [project['repo'] for project in using],
        'live': {'at': last['at'], 'repo': repo_of[last['projectId']], 'checks': [{'action': str(check.get('action')), 'allowed': check.get('allowed') is True} for check in last['checks']]} if last else None,
    }


def bootstrap_for(cloud, repo, data, trust):
    name = project_slug(repo)
    replacements = {
        '__REPO__': repo, '__NAME__': name, '__ISSUER__': trust['issuer'], '__GCP_ISSUER__': trust['gcpIssuer'],
        '__AWS_AUDIENCE__': trust['awsAudience'], '__GCP_AUDIENCE__': trust['gcpAudience'], '__SUBJECT__': trust['subject'], '__GCP_CONDITION__': trust['gcpCondition'],
    }

    def fill(template):
        for key, value in replacements.items():
            template = template.replace(key, value)
        return template

    if cloud == 'aws':
        return fill(TEMPLATES['bootstrap-aws.yml'])
    return fill(TEMPLATES['bootstrap-gcp.sh']).replace('__PROJECT__', data['projectId']).replace('__REGION__', data['region'])


# Where each provider's CI reads its pipeline. GitLab and Bitbucket use one file at the repo root,
# so an existing one is left alone and the PR explains what to add.
CI_FILES = {
    'github': [{'path': '.github/workflows/cloudhop.yml', 'template': 'workflow.yml'}],
    'gitlab': [{'path': '.gitlab-ci.yml', 'template': 'gitlab-ci.yml', 'fallback': '.cloudhop/gitlab-ci.yml', 'note': 'This repo already has .gitlab-ci.yml. Add `include: { local: .cloudhop/gitlab-ci.yml }` to it. The Cloudhop job only runs when Cloudhop starts a pipeline.'}],
    'bitbucket': [{'path': 'bitbucket-pipelines.yml', 'template': 'bitbucket-pipelines.yml', 'fallback': '.cloudhop/bitbucket-pipelines.yml', 'note': 'This repo already has bitbucket-pipelines.yml. Copy the `custom: cloudhop` pipeline from .cloudhop/bitbucket-pipelines.yml into it.'}],
    'azure': [{'path': '.cloudhop/azure-pipelines.yml', 'template': 'azure-pipelines.yml'}],
}


def install_files(repo, service_map, clouds, cloudhop_url, provider='github', existing_paths=frozenset()):
    services = app_services(service_map)
    by_path = {service['path']: service for service in service_map['services']}
    config = {
        'name': resource_name(repo),
        'repo': repo,
        'cloudhopUrl': cloudhop_url,
        'hasPostgres': any(store['kind'] == 'postgres' for store in service_map['datastores']),
        'services': services,
        'clouds': clouds,
    }
    notes = []
    files = []
    for ci in CI_FILES[provider]:
        taken = bool(ci.get('fallback')) and ci['path'] in existing_paths
        files.append({'path': ci['fallback'] if taken else ci['path'], 'content': TEMPLATES[ci['template']]})
        if taken:
            notes.append(ci['note'])
    if provider != 'github':
        files.append({'path': '.cloudhop/ci.sh', 'content': TEMPLATES['ci.sh'], 'executable': True})
    files += [
        {'path': '.cloudhop/run.sh', 'content': TEMPLATES['run.sh'], 'executable': True},
        {'path': '.cloudhop/config.json', 'content': json.dumps(config, indent=2, ensure_ascii=False) + '\n'},
        {'path': '.cloudhop/compose.yml', 'content': compose_for(service_map)},
        {'path': '.cloudhop/infra/aws/main.tf', 'content': TEMPLATES['aws.tf']},
        {'path': '.cloudhop/infra/gcp/main.tf', 'content': TEMPLATES['gcp.tf']},
    ]
    for service in services:
        source = by_path[service['path']]
        if not source['hasDockerfile']:
            files.append({'path': 'Dockerfile' if service['path'] == '.' else f"{service['path']}/Dockerfile", 'content': dockerfile_for(source)})
    return {'files': files, 'notes': notes}
