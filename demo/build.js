// Builds the GitHub Pages demo: the real dashboard from frontend/public plus demo.js, which answers
// /api calls in the browser with sample data. demo.js runs engine/, a frozen JavaScript copy of the
// backend logic, and the real setup-file templates from backend/templates.
// Usage: node demo/build.js <out-dir>   (the site is published under <out-dir>/demo/)
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = process.argv[2] ?? '_site';
const site = join(out, 'demo');
const publicDir = new URL('../frontend/public/', import.meta.url);
const engine = new URL('./engine/', import.meta.url);
const templatesDir = new URL('../backend/templates/', import.meta.url);
// Dependency order: each module may import only from those before it.
const MODULES = ['templates.gen.js', 'analyze.js', 'store.js', 'portability.js', 'plans.js', 'intent.js', 'generate.js', 'github.js', 'providers.js'];

const templates = Object.fromEntries(readdirSync(templatesDir).map((name) => [name, readFileSync(new URL(name, templatesDir), 'utf8').replaceAll('\r\n', '\n')]));
const sources = { 'templates.gen.js': `export const TEMPLATES = ${JSON.stringify(templates)};\n` };
const read = (name) => sources[name] ?? readFileSync(new URL(name, engine), 'utf8');

// A tiny bundler for our own plain ES modules: each file becomes a function returning its exports.
function wrap(name, source) {
  const imports = [...source.matchAll(/^import \{([^}]+)\} from '\.\/([^']+)';$/gm)];
  const names = [];
  const body = source
    .replace(/^import .*$/gm, '')
    .replace(/^export (async function|function|const|let|class) (\w+)/gm, (_, kind, id) => { names.push(id); return `${kind} ${id}`; });
  const header = imports.map(([, list, from]) => `const {${list}} = modules['${from}'];`).join('\n');
  return `modules['${name}'] = (() => {\n${header}\n${body}\nreturn { ${names.join(', ')} };\n})();`;
}

const bundle = [
  '// Generated by demo/build.js. Demo only: answers /api calls with sample data.',
  '(() => {',
  'const modules = {};',
  // Browsers refuse a custom User-Agent header, so drop it from GitHub calls made by the shared modules.
  'const browserFetch = window.fetch.bind(window);',
  'const fetch = (url, options = {}) => { const headers = { ...(options.headers ?? {}) }; delete headers["User-Agent"]; return browserFetch(url, { ...options, headers }); };',
  ...MODULES.map((name) => wrap(name, read(name))),
  readFileSync(new URL('mock.js', import.meta.url), 'utf8'),
  '})();',
].join('\n');

mkdirSync(site, { recursive: true });
for (const file of readdirSync(publicDir)) {
  if (file === '_headers') continue; // Served by the real backend, not GitHub Pages.
  copyFileSync(new URL(file, publicDir), join(site, file));
}
writeFileSync(join(site, 'demo.js'), bundle);
const index = readFileSync(new URL('index.html', publicDir), 'utf8');
if (!index.includes('<script src="charts.js"></script>')) throw new Error('index.html changed: update the demo script injection');
writeFileSync(join(site, 'index.html'), index
  .replace('<title>Cloudhop</title>', '<title>Cloudhop demo</title>')
  .replace('<script src="charts.js"></script>', '<script src="demo.js"></script>\n<script src="charts.js"></script>'));
// The site root sends visitors on to the demo.
writeFileSync(join(out, 'index.html'), '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=demo/"><title>Cloudhop</title><a href="demo/">Cloudhop demo</a>\n');
writeFileSync(join(out, '.nojekyll'), '');
console.log(`Demo built in ${site}`);
