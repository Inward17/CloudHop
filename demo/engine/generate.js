// Turns a service map into the files committed to the user's repo, for review in a PR.
import { TEMPLATES } from './templates.gen.js';

const DEPLOYABLE_STORES = new Set(['postgres', 'redis']);

export function deployIssues(map) {
  const issues = [];
  if (map.services.length === 0) issues.push('No runnable service was found.');
  for (const store of map.datastores) {
    if (!DEPLOYABLE_STORES.has(store.kind)) issues.push(`${store.kind} cannot be deployed yet. Postgres and Redis work.`);
  }
  for (const service of map.services) {
    if (service.runtime !== 'node' && service.runtime !== 'python' && !service.hasDockerfile) {
      issues.push(`${service.path} needs a Dockerfile, because ${service.runtime} has no built-in build support.`);
    }
  }
  return issues;
}

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Short and unique per repo, so two projects named "app" under different owners never share cloud names.
export function projectSlug(repo) {
  let hash = 2166136261;
  for (const char of repo.toLowerCase()) hash = Math.imul(hash ^ char.charCodeAt(0), 16777619) >>> 0;
  return `${slug(repo.split('/').at(-1)).slice(0, 16).replace(/-$/, '')}-${hash.toString(36).slice(0, 4)}`;
}

export function resourceName(repo) {
  return `cloudhop-${projectSlug(repo)}`;
}

function servicePort(service) {
  if (service.port) return service.port;
  if (service.kind === 'static') return 80;
  return service.runtime === 'python' ? 8000 : 3000;
}

const PYTHON_START = {
  FastAPI: (port) => `["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "${port}"]`,
  Flask: (port) => `["flask", "run", "--host", "0.0.0.0", "--port", "${port}"]`,
  Django: (port) => `["python", "manage.py", "runserver", "0.0.0.0:${port}"]`,
};

export function dockerfileFor(service) {
  const port = servicePort(service);
  const review = '# Generated by Cloudhop. Check the start command before merging.\n';
  if (service.kind === 'static') {
    const output = service.framework === 'Create React App' ? 'build' : 'dist';
    return `${review}FROM node:22-slim AS build\nWORKDIR /app\nCOPY . .\nRUN npm ci || npm install\nRUN npm run build\n\nFROM nginx:alpine\nCOPY --from=build /app/${output} /usr/share/nginx/html\nEXPOSE 80\n`;
  }
  if (service.runtime === 'python') {
    const start = (PYTHON_START[service.framework] ?? PYTHON_START.FastAPI)(port);
    return `${review}FROM python:3.12-slim\nWORKDIR /app\nCOPY . .\nRUN if [ -f requirements.txt ]; then pip install -r requirements.txt; else pip install .; fi\nENV PORT=${port}\nEXPOSE ${port}\nCMD ${start}\n`;
  }
  return `${review}FROM node:22-slim\nWORKDIR /app\nCOPY . .\nRUN npm ci || npm install\nRUN npm run build --if-present\nENV PORT=${port}\nEXPOSE ${port}\nCMD ["npm", "start"]\n`;
}

export function appServices(map) {
  // First web service gets port 80, so a backend beats a static frontend for the main address.
  const ordered = [...map.services].sort((a, b) => (a.kind === 'web' ? 0 : 1) - (b.kind === 'web' ? 0 : 1));
  return ordered.map((service, index) => ({
    name: service.path === '.' ? 'app' : `app-${slug(service.path)}`,
    path: service.path,
    port: servicePort(service),
    publicPort: index === 0 ? 80 : 8080 + index,
  }));
}

export function composeFor(map) {
  const hasPostgres = map.datastores.some((store) => store.kind === 'postgres');
  const hasRedis = map.datastores.some((store) => store.kind === 'redis');
  const dependsOn = [...(hasPostgres ? ['db'] : []), ...(hasRedis ? ['redis'] : [])];
  const env = [
    ...(hasPostgres ? ['      DATABASE_URL: postgres://app:${DB_PASSWORD}@db:5432/app'] : []),
    ...(hasRedis ? ['      REDIS_URL: redis://redis:6379'] : []),
  ];
  const lines = ['# Generated by Cloudhop.', 'services:'];
  for (const service of appServices(map)) {
    lines.push(
      `  ${service.name}:`,
      `    build: ./src${service.path === '.' ? '' : '/' + service.path}`,
      '    restart: unless-stopped',
      '    env_file: .env',
      `    ports: ["${service.publicPort}:${service.port}"]`,
    );
    if (env.length) lines.push('    environment:', ...env);
    if (dependsOn.length) lines.push(`    depends_on: [${dependsOn.join(', ')}]`);
  }
  if (hasPostgres) {
    lines.push(
      '  db:',
      '    image: postgres:16',
      '    restart: unless-stopped',
      '    environment:',
      '      POSTGRES_USER: app',
      '      POSTGRES_DB: app',
      '      POSTGRES_PASSWORD: ${DB_PASSWORD}',
      '    volumes: [db:/var/lib/postgresql/data]',
      '    healthcheck:',
      '      test: [CMD, pg_isready, -U, app]',
      '      interval: 5s',
      '      retries: 20',
    );
  }
  if (hasRedis) lines.push('  redis:', '    image: redis:7', '    restart: unless-stopped');
  if (hasPostgres) lines.push('volumes:', '  db:');
  return lines.join('\n') + '\n';
}

// Role, pool and service account are named per project, so several projects can share one cloud account.
export function cloudConfig(cloud, input, repo) {
  const name = projectSlug(repo);
  if (cloud === 'aws') {
    return {
      region: input.region,
      accountId: input.accountId,
      roleArn: `arn:aws:iam::${input.accountId}:role/cloudhop-${name}-deploy`,
      stateBucket: `cloudhop-state-${input.accountId}`,
    };
  }
  return {
    region: input.region,
    projectId: input.projectId,
    projectNumber: input.projectNumber,
    workloadIdentityProvider: `projects/${input.projectNumber}/locations/global/workloadIdentityPools/ch-${name}/providers/ci`,
    serviceAccount: `ch-${name}@${input.projectId}.iam.gserviceaccount.com`,
    stateBucket: `${input.projectId}-cloudhop-state`,
  };
}

/* Which CI identity the clouds trust. Each CI issues its own OIDC tokens; AWS and GCP accept a
   token only from this repo (and branch or environment where the CI puts that in the token). */

const SAFE = /^[\w.\-/{}:* ]+$/;

export function trustFor(provider, info) {
  let trust;
  if (provider === 'github') {
    const subject = `repo:${info.repo}:environment:cloudhop`;
    trust = { issuer: 'token.actions.githubusercontent.com', gcpIssuer: 'https://token.actions.githubusercontent.com', awsAudience: 'sts.amazonaws.com', gcpAudience: '', subject, gcpCondition: `assertion.sub == '${subject}'` };
  } else if (provider === 'gitlab') {
    const subject = `project_path:${info.repo}:ref_type:branch:ref:${info.defaultBranch}`;
    trust = { issuer: 'gitlab.com', gcpIssuer: 'https://gitlab.com/', awsAudience: 'https://gitlab.com', gcpAudience: 'https://gitlab.com', subject, gcpCondition: `assertion.sub == '${subject}'` };
  } else if (provider === 'bitbucket') {
    const issuer = `api.bitbucket.org/2.0/workspaces/${info.workspace}/pipelines-config/identity/oidc`;
    const audience = `ari:cloud:bitbucket::workspace/${info.workspaceUuid.replace(/[{}]/g, '')}`;
    trust = { issuer, gcpIssuer: `https://${issuer}`, awsAudience: audience, gcpAudience: audience, subject: `${info.repositoryUuid}*`, gcpCondition: `assertion.sub.startsWith('${info.repositoryUuid}')` };
  } else if (provider === 'azure') {
    const subject = `sc://${info.organization}/${info.project}/cloudhop`;
    const issuer = `vstoken.dev.azure.com/${info.organizationId}`;
    trust = { issuer, gcpIssuer: `https://${issuer}`, awsAudience: 'api://AzureADTokenExchange', gcpAudience: 'api://AzureADTokenExchange', subject, gcpCondition: `assertion.sub == '${subject}'` };
  } else {
    throw new Error(`Unknown provider ${provider}`);
  }
  // These values go into a CloudFormation file and a shell script, so refuse anything that could break out.
  for (const value of [trust.issuer, trust.awsAudience, trust.gcpAudience, trust.subject]) {
    if (value && !SAFE.test(value)) throw new Error('Repository details contain characters Cloudhop cannot put in a setup file');
  }
  return trust;
}

// These values end up in generated files and scripts, so only safe characters pass.
export function validateCloudInput(cloud, input) {
  const region = /^[a-z]+-[a-z]+\d?(-\d)?$/.test(input?.region ?? '');
  if (cloud === 'aws') return region && /^\d{12}$/.test(input?.accountId ?? '');
  if (cloud === 'gcp') return region && /^[a-z][a-z0-9-]{4,28}[a-z0-9]$/.test(input?.projectId ?? '') && /^\d{6,20}$/.test(input?.projectNumber ?? '');
  return false;
}

/* What the setup files grant, in plain words. Keep in step with bootstrap-aws.yml and bootstrap-gcp.sh. */
export const CLOUD_GRANTS = {
  aws: [
    ['EC2, all actions', 'Create, change and delete servers, disks, networks and firewalls anywhere in the account.'],
    ['Systems Manager', 'Run commands on servers and read parameters.'],
    ['S3', 'Only buckets named cloudhop-*.'],
    ['IAM', 'Only roles and instance profiles named cloudhop-*-vm, and checking its own permissions. It cannot change its own role.'],
    ['Billing', 'Read month-to-date cost and credits.'],
  ],
  gcp: [
    ['Compute Admin', 'Create, change and delete VMs, disks, networks and firewalls anywhere in the project.'],
    ['Storage Admin', 'Every bucket in the project.'],
    ['Service Account Admin and User', 'Create service accounts and run VMs as them.'],
    ['IAP tunnel and OS Admin Login', 'Reach VMs through IAP and sign in to them as admin.'],
  ],
};

// A cloud account's access: what its setup file grants, which repos' CI can use it, and the
// latest live permission check reported by a verify run. `account.data` and `project.clouds` are parsed.
export function projectsUsingCloud(account, projects) {
  const key = account.kind === 'aws' ? 'accountId' : 'projectId';
  return projects.filter((project) => project.clouds[account.kind]?.[key] === account.data[key]);
}

export function cloudAccess(account, projects, reports) {
  const using = projectsUsingCloud(account, projects);
  const repoOf = new Map(using.map((project) => [project.id, project.repo]));
  const last = reports
    .filter((report) => report.event === 'access' && report.cloud === account.kind && repoOf.has(report.projectId) && Array.isArray(report.checks))
    .sort((a, b) => b.at - a.at)[0];
  return {
    kind: 'cloud',
    grants: CLOUD_GRANTS[account.kind],
    repos: using.map((project) => project.repo),
    live: last ? { at: last.at, repo: repoOf.get(last.projectId), checks: last.checks.map((check) => ({ action: String(check.action), allowed: check.allowed === true })) } : null,
  };
}

export function bootstrapFor(cloud, repo, input, trust) {
  const name = projectSlug(repo);
  const fill = (template) => template
    .replaceAll('__REPO__', repo).replaceAll('__NAME__', name).replaceAll('__ISSUER__', trust.issuer)
    .replaceAll('__GCP_ISSUER__', trust.gcpIssuer).replaceAll('__AWS_AUDIENCE__', trust.awsAudience).replaceAll('__GCP_AUDIENCE__', trust.gcpAudience)
    .replaceAll('__SUBJECT__', trust.subject).replaceAll('__GCP_CONDITION__', trust.gcpCondition);
  if (cloud === 'aws') return fill(TEMPLATES['bootstrap-aws.yml']);
  return fill(TEMPLATES['bootstrap-gcp.sh']).replaceAll('__PROJECT__', input.projectId).replaceAll('__REGION__', input.region);
}

// Where each provider's CI reads its pipeline. GitLab and Bitbucket use one file at the repo root,
// so an existing one is left alone and the PR explains what to add.
const CI_FILES = {
  github: [{ path: '.github/workflows/cloudhop.yml', template: 'workflow.yml' }],
  gitlab: [{ path: '.gitlab-ci.yml', template: 'gitlab-ci.yml', fallback: '.cloudhop/gitlab-ci.yml', note: 'This repo already has .gitlab-ci.yml. Add `include: { local: .cloudhop/gitlab-ci.yml }` to it. The Cloudhop job only runs when Cloudhop starts a pipeline.' }],
  bitbucket: [{ path: 'bitbucket-pipelines.yml', template: 'bitbucket-pipelines.yml', fallback: '.cloudhop/bitbucket-pipelines.yml', note: 'This repo already has bitbucket-pipelines.yml. Copy the `custom: cloudhop` pipeline from .cloudhop/bitbucket-pipelines.yml into it.' }],
  azure: [{ path: '.cloudhop/azure-pipelines.yml', template: 'azure-pipelines.yml' }],
};

export function installFiles({ provider = 'github', repo, map, clouds, cloudhopUrl, existingPaths = new Set() }) {
  const services = appServices(map);
  const byPath = new Map(map.services.map((service) => [service.path, service]));
  const config = {
    name: resourceName(repo),
    repo,
    cloudhopUrl,
    hasPostgres: map.datastores.some((store) => store.kind === 'postgres'),
    services,
    clouds,
  };
  const notes = [];
  const files = [];
  for (const ci of CI_FILES[provider]) {
    const taken = ci.fallback && existingPaths.has(ci.path);
    files.push({ path: taken ? ci.fallback : ci.path, content: TEMPLATES[ci.template] });
    if (taken) notes.push(ci.note);
  }
  if (provider !== 'github') files.push({ path: '.cloudhop/ci.sh', content: TEMPLATES['ci.sh'], executable: true });
  files.push(
    { path: '.cloudhop/run.sh', content: TEMPLATES['run.sh'], executable: true },
    { path: '.cloudhop/config.json', content: JSON.stringify(config, null, 2) + '\n' },
    { path: '.cloudhop/compose.yml', content: composeFor(map) },
    { path: '.cloudhop/infra/aws/main.tf', content: TEMPLATES['aws.tf'] },
    { path: '.cloudhop/infra/gcp/main.tf', content: TEMPLATES['gcp.tf'] },
  );
  for (const service of services) {
    const source = byPath.get(service.path);
    if (!source.hasDockerfile) {
      files.push({ path: service.path === '.' ? 'Dockerfile' : `${service.path}/Dockerfile`, content: dockerfileFor(source) });
    }
  }
  return { files, notes };
}
